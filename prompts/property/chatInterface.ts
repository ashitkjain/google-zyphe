import { PropertyData, CustomAIAnalysisResult, ComprehensiveAnalysisResult } from "../../types";
import { optimizePropertyForAi, optimizeVisualForAi } from "../../utils/aiOptimization";

export const getChatContext = (property: PropertyData, visual: CustomAIAnalysisResult | null, comprehensive: ComprehensiveAnalysisResult | null) => {
    // 1. Optimize raw property data
    const optimizedProperty = optimizePropertyForAi(property);

    // 2. Optimize visual data but preserve image_by_image_analysis for visual grounding
    let optimizedVisual: any = visual ? { ...optimizeVisualForAi(visual) } : null;
    if (visual?.image_by_image_analysis && optimizedVisual) {
        optimizedVisual.imageAnalysis = visual.image_by_image_analysis.map((img, idx) => ({
            index: idx,
            summary: img.analysis.slice(0, 150) + "..." // Truncate to save tokens
        }));
    }

    return {
        ...optimizedProperty,
        visualIntelligence: optimizedVisual || "Visual analysis not yet generated by the user.",
        communityPulse: visual?.community_pulse || comprehensive?.detailed_analysis?.community_pulse || "Community pulse data not yet fully integrated for this area.",
        propertyInvestment: visual?.property_investment || "Investment yield data not yet available.",
        generalMarketIntelligence: visual?.general_market_intelligence ? (({ web_sources, ...rest }) => rest)(visual.general_market_intelligence as any) : "General market trends not yet analyzed.",
        narrativeReport: comprehensive ? {
            summary: comprehensive.summary,
            detailedAnalysis: comprehensive.detailed_analysis,
            strategicInsights: comprehensive.strategic_insights,
            risksAndConsiderations: comprehensive.risks_considerations
        } : "Comprehensive narrative not yet generated by the user."
    };
};

