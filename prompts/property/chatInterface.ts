import { PropertyData, CustomAIAnalysisResult, ComprehensiveAnalysisResult } from "../../types";

export const getChatContext = (property: PropertyData, visual: CustomAIAnalysisResult | null, comprehensive: ComprehensiveAnalysisResult | null) => {
    return {
        address: property.address,
        financials: {
            price: property.price,
            zestimate: property.zestimate,
            rent: property.rentZestimate,
            tax: property.propertyTaxRate,
            insurance: property.annualHomeownersInsurance
        },
        specifications: {
            type: property.homeType,
            beds: property.bedrooms,
            baths: property.bathrooms,
            livingArea: property.livingAreaValue,
            lotSize: property.lotSize,
            yearBuilt: property.yearBuilt,
            status: property.homeStatus,
            details: property.resoFacts
        },
        mobility: {
            walk: property.walkScore,
            walkDesc: property.walkScoreDesc,
            transit: property.transitScore,
            transitDesc: property.transitScoreDesc,
            bike: property.bikeScore,
            bikeDesc: property.bikeScoreDesc
        },
        risks: {
            flood: property.floodRiskScore,
            wind: property.windRiskScore,
            fire: property.fireRiskScore,
            heat: property.heatRiskScore
        },
        schools: property.schools?.map(s => `${s.name} (${s.level}): Rating ${s.rating}/10, Distance ${s.distance}`),
        visualIntelligence: visual || "Visual analysis not yet generated by the user.",
        marketResearch: visual?.investment_research ? {
            investment: visual.investment_research.property_specific,
            marketDynamics: visual.investment_research.general?.market_dynamics,
            demandDrivers: visual.investment_research.general?.demand_drivers
        } : "Market research data not yet available for this property.",
        communityPulse: visual?.community_pulse ? {
            lifestyle: visual.community_pulse.lifestyle_convenience,
            residentSentiment: visual.community_pulse.what_residents_like,
            localComplaints: visual.community_pulse.common_complaints,
            safety: visual.community_pulse.safety_and_concerns,
            familyFriendliness: visual.community_pulse.schools_family_friendliness
        } : "Community pulse data not yet fully integrated for this area.",
        narrativeReport: comprehensive ? {
            summary: comprehensive.summary,
            lifestyleFit: comprehensive.detailed_analysis?.location_neighborhood, // Mapping to available data
            recommendation: comprehensive.risks_considerations
        } : "Comprehensive narrative not yet generated by the user."
    };
};

